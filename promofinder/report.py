"""
Write the run out in three shapes, for three readers.

  promos.json  - everything, for the next tool in the chain
  promos.csv   - one row per promo, for an editor working in a spreadsheet
  promos.md    - the ranked list a human actually reads
  run_report.json - parse warnings, rejects, failed batches, token usage

The CSV is the one an editor opens, so its columns are the ones an editor
needs: where to cut, what the hook is, and why it was picked.
"""

from __future__ import annotations

import csv
import json
import os
from typing import Dict, List, Optional

from .parse import Episode, fmt_timestamp
from .segment import Candidate


def _segment_string(cand: Candidate) -> str:
    return " + ".join(
        "ep%d %s-%s" % (s.episode, fmt_timestamp(s.start), fmt_timestamp(s.end))
        for s in cand.segments
    )


def row_to_dict(row: dict) -> dict:
    cand: Candidate = row["candidate"]
    j: dict = row["judgement"]
    return {
        "rank": row.get("rank"),
        "id": cand.cand_id,
        "kind": cand.kind,
        "episodes": cand.episodes,
        "segments": [s.to_dict() for s in cand.segments],
        "total_duration_s": round(cand.duration, 2),
        "score": round(row["score"], 3),
        "hook": j.get("hook", ""),
        "cliffhanger": j.get("cliffhanger", ""),
        "why": j.get("why", ""),
        "risk": j.get("risk", ""),
        "verdict": j.get("verdict", ""),
        "scores": {
            "hook_strength": j.get("hook_strength"),
            "cliffhanger_strength": j.get("cliffhanger_strength"),
            "standalone_clarity": j.get("standalone_clarity"),
            "emotional_punch": j.get("emotional_punch"),
        },
        "rule_signals": {k: round(v, 3) for k, v in cand.signals.items()},
    }


def write_json(path: str, rows: List[dict], meta: dict) -> None:
    payload = {"meta": meta, "promos": [row_to_dict(r) for r in rows]}
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, ensure_ascii=False)


def write_csv(path: str, rows: List[dict]) -> None:
    cols = ["rank", "id", "episodes", "segments", "duration_s", "score",
            "verdict", "hook", "cliffhanger", "why", "risk",
            "hook_strength", "cliffhanger_strength", "standalone_clarity",
            "emotional_punch"]
    with open(path, "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(cols)
        for r in rows:
            cand: Candidate = r["candidate"]
            j: dict = r["judgement"]
            w.writerow([
                r.get("rank"),
                cand.cand_id,
                " / ".join(str(e) for e in cand.episodes),
                _segment_string(cand),
                round(cand.duration, 2),
                round(r["score"], 3),
                j.get("verdict", ""),
                j.get("hook", ""),
                j.get("cliffhanger", ""),
                j.get("why", ""),
                j.get("risk", ""),
                j.get("hook_strength"),
                j.get("cliffhanger_strength"),
                j.get("standalone_clarity"),
                j.get("emotional_punch"),
            ])


def write_markdown(path: str, rows: List[dict], meta: dict,
                   episodes: Dict[int, Episode]) -> None:
    out: List[str] = []
    out.append("# Promo shortlist: %s" % meta.get("show", "unknown show"))
    out.append("")
    out.append("Scored by %s on %d episodes. %d candidates generated by rules, "
               "%d judged, top %d listed."
               % (meta.get("scorer", "?"), meta.get("episodes", 0),
                  meta.get("candidates", 0), meta.get("judged", 0), len(rows)))
    out.append("")
    out.append("Timestamps are MM:SS.ss within the named episode. "
               "Every cut lands on a line or action boundary from the script.")
    out.append("")

    for r in rows:
        cand: Candidate = r["candidate"]
        j: dict = r["judgement"]
        out.append("## %d. %s" % (r.get("rank", 0), _segment_string(cand)))
        out.append("")
        out.append("- **Length:** %.1fs%s" % (
            cand.duration, " (two segments joined)" if cand.kind == "stitched" else ""))
        out.append("- **Hook:** %s" % j.get("hook", ""))
        out.append("- **Cliffhanger:** %s" % j.get("cliffhanger", ""))
        out.append("- **Why it works:** %s" % j.get("why", ""))
        out.append("- **Weakness:** %s" % j.get("risk", ""))
        out.append("- **Scores:** hook %s, cliffhanger %s, standalone %s, punch %s "
                   "-> %.2f (%s)" % (
                       j.get("hook_strength"), j.get("cliffhanger_strength"),
                       j.get("standalone_clarity"), j.get("emotional_punch"),
                       r["score"], j.get("verdict", "")))
        ep = episodes.get(cand.episodes[0]) if cand.episodes else None
        if ep is not None and ep.logline:
            out.append("- **Episode context:** %s" % ep.logline)
        out.append("")

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))


def write_run_report(path: str, meta: dict, episodes: List[Episode],
                     rejects: List[dict], failures: List[dict]) -> None:
    report = {
        "meta": meta,
        "parse": {
            "episodes": len(episodes),
            "blocks": sum(len(e.blocks) for e in episodes),
            "warnings": [
                {"episode": e.number, "warning": w}
                for e in episodes for w in e.warnings
            ],
        },
        "candidate_rejects": rejects,
        "scoring_failures": failures,
    }
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2, ensure_ascii=False)


def write_all(out_dir: str, rows: List[dict], meta: dict,
              episodes: List[Episode], rejects: List[dict],
              failures: List[dict],
              all_rows: Optional[List[dict]] = None) -> Dict[str, str]:
    os.makedirs(out_dir, exist_ok=True)
    ep_map = {e.number: e for e in episodes}
    paths = {
        "json": os.path.join(out_dir, "promos.json"),
        "csv": os.path.join(out_dir, "promos.csv"),
        "markdown": os.path.join(out_dir, "promos.md"),
        "report": os.path.join(out_dir, "run_report.json"),
    }
    write_json(paths["json"], rows, meta)
    write_csv(paths["csv"], rows)
    write_markdown(paths["markdown"], rows, meta, ep_map)
    write_run_report(paths["report"], meta, episodes, rejects, failures)

    if all_rows is not None:
        # Every judged clip in score order, including the ones that did not make
        # the published list. The eval needs these to see what got buried.
        for i, r in enumerate(all_rows, start=1):
            r.setdefault("rank", i)
        paths["json_all"] = os.path.join(out_dir, "promos_all.json")
        write_json(paths["json_all"], all_rows, dict(meta, note="full ranking"))
    return paths
